//! Build script: font rasterization.
//!
//! Fonts are rasterized here (fontdue) into 8-bit coverage bitmaps, matching what the old
//! `tools/gen_fonts.py` produced: `yo` is the offset from the top of the ascender box, `xo` from the
//! pen position. Output: `$OUT_DIR/fonts.rs` (tables) + one .bin per font (bitmaps).

use std::{env, fmt::Write as _, fs, path::PathBuf};

const UPPER: &str = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789:+-/x>%.#ÁÉÍÓÚÑÜ_·";
const LATIN_EXTRA: &str = "áéíóúüñÁÉÍÓÚÜÑàèìòùâêîôûäëïöçÀÈÌÒÙÄËÏÖÇ¡¿·–—’“”…";

struct Spec {
    name: &'static str,
    file: &'static str,
    px: f32,
    upper_only: bool,
}

const FONTS: &[Spec] = &[
    Spec { name: "BIG", file: "JetBrainsMono-Bold.ttf", px: 40.0, upper_only: false },
    Spec { name: "HEAD", file: "JetBrainsMono-SemiBold.ttf", px: 24.0, upper_only: false },
    Spec { name: "TITLE", file: "JetBrainsMono-SemiBold.ttf", px: 20.0, upper_only: false },
    Spec { name: "SUB", file: "JetBrainsMono-Regular.ttf", px: 15.0, upper_only: false },
    Spec { name: "TAG", file: "JetBrainsMono-Bold.ttf", px: 12.0, upper_only: true },
];

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let fonts_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("assets/fonts");
    println!("cargo:rerun-if-changed=assets/fonts");
    println!("cargo:rerun-if-changed=build.rs");

    let latin: String = (32u8..127).map(char::from).chain(LATIN_EXTRA.chars()).collect();
    let mut src = String::from("// Generated by build.rs — do not edit.\n");

    for spec in FONTS {
        let bytes = fs::read(fonts_dir.join(spec.file)).expect("font file");
        let font = fontdue::Font::from_bytes(bytes, fontdue::FontSettings::default()).expect("font");
        let ascent = font.horizontal_line_metrics(spec.px).expect("line metrics").ascent.round() as i32;
        let chars: Vec<char> = if spec.upper_only { UPPER.chars().collect() } else { latin.chars().collect() };

        let mut data: Vec<u8> = Vec::new();
        let mut glyphs = String::new();
        let mut lut = [0u8; 256]; // Latin-1 code → glyph index + 1
        for (i, &ch) in chars.iter().enumerate() {
            let (m, bitmap) = font.rasterize(ch, spec.px);
            let adv = m.advance_width.round() as i32;
            let (w, h) = (m.width as i32, m.height as i32);
            let (xo, yo) = if w == 0 || h == 0 { (0, 0) } else { (m.xmin, ascent - (m.ymin + h)) };
            writeln!(
                glyphs,
                "    Glyph {{ off: {}, w: {w}, h: {h}, xo: {xo}, yo: {yo}, adv: {adv}, code: {} }},",
                data.len(),
                ch as u32
            )
            .unwrap();
            if w > 0 && h > 0 {
                data.extend_from_slice(&bitmap);
            }
            if (ch as u32) < 256 {
                lut[ch as usize] = (i + 1) as u8;
            }
        }
        let bin = format!("font_{}.bin", spec.name.to_lowercase());
        fs::write(out.join(&bin), &data).unwrap();
        write!(
            src,
            "pub static {name}: Font = Font {{\n  glyphs: &[\n{glyphs}  ],\n  data: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{bin}\")),\n  ascent: {ascent},\n  latin: {lut:?},\n}};\n",
            name = spec.name,
        )
        .unwrap();
    }
    fs::write(out.join("fonts.rs"), src).unwrap();
}
